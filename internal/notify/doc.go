// Package notify 实现事件中心：
// 系统异常事件写库并按 key 去重合并（count++、刷新 last_at），同一事件
// 在冷却窗口（默认 30 分钟）内只经 Bot API 推送一次管理员私聊通知；
// 只有发送成功才记录冷却时间，失败只记日志并保留后续重试机会。
// 事件被标记解决（人工或系统自动恢复）后再次发生会重新触发通知。
//
// 依赖边界：本包依赖 store 与 delivery 的最小接口，不反向依赖任何事件源——
// mtproto / queue 通过各自的观察者接口把状态变化喂给 Hub，由装配层（main）接线，
// 避免 MTProto / 队列实现感知通知细节。通知发送失败只记日志，绝不阻塞主链路；
// Hub 不推进失败通知的冷却时间，后续事件或通道恢复时可重试。
package notify
